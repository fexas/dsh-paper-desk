/** Obsidian-flavoured Markdown with native MathML formula rendering. */
import { Marked } from 'marked';
import katex from 'katex';
import DOMPurify from 'dompurify';

const INLINE_MATH = /^(?:\$(?![\s$])((?:\\.|[^$\n])+?)(?<!\s)\$(?!\d)|\\\(((?:\\.|[^\\])+?)\\\))/;
const BLOCK_MATH = /^(?:\$\$([\s\S]+?)\$\$|\\\[([\s\S]+?)\\\])[ \t]*(?:\n+|$)/;

function escapeHtml(value) {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function renderMath(latex, display) {
  try {
    // MathML is supported natively by Chromium/Electron, so no font files or
    // KaTeX CSS need to be shipped inside the plugin. KaTeX still handles the
    // TeX parser and produces accessible, scalable markup.
    const rendered = katex.renderToString(String(latex || '').trim(), {
      displayMode: Boolean(display),
      output: 'htmlAndMathml',
      throwOnError: false,
      strict: 'ignore',
      trust: false,
      errorColor: '#d14b4b',
    });
    return display
      ? `<div class="pd-math-block">${rendered}</div>`
      : `<span class="pd-math-inline">${rendered}</span>`;
  } catch {
    return `<code class="pd-math-error">${escapeHtml(latex)}</code>`;
  }
}

function createRenderer() {
  const math = [];
  const placeholder = (latex, display) => {
    const index = math.length;
    math.push(renderMath(latex, display));
    return `PDMATHTOKEN${index}ZZ`;
  };
  const instance = new Marked({ gfm: true, breaks: true, async: false });
  instance.use({
    extensions: [
      {
        name: 'blockMath',
        level: 'block',
        start(src) {
          const match = src.match(/\$\$|\\\[/);
          return match ? match.index : undefined;
        },
        tokenizer(src) {
          const match = BLOCK_MATH.exec(src);
          if (!match) return undefined;
          return {
            type: 'blockMath',
            raw: match[0],
            text: (match[1] ?? match[2] ?? '').trim(),
            display: true,
          };
        },
        renderer(token) {
          return placeholder(token.text, true);
        },
      },
      {
        name: 'inlineMath',
        level: 'inline',
        start(src) {
          const match = src.match(/\$|\\\(|\\\[/);
          return match ? match.index : undefined;
        },
        tokenizer(src) {
          // A display pair at the start of an inline run is still display.
          const display = /^\$\$([\s\S]+?)\$\$/.exec(src);
          if (display) {
            return { type: 'inlineMath', raw: display[0], text: display[1].trim(), display: true };
          }
          const match = INLINE_MATH.exec(src);
          if (!match) return undefined;
          return {
            type: 'inlineMath',
            raw: match[0],
            text: (match[1] ?? match[2] ?? '').trim(),
            display: false,
          };
        },
        renderer(token) {
          return placeholder(token.text, token.display);
        },
      },
    ],
  });
  return { instance, math };
}

function prepare(source) {
  return String(source || '')
    .replace(/==([^=\n]+)==/g, '<mark>$1</mark>')
    .replace(/^>\s*\[!([^\]]+)\]\s*$/gm, '> **$1**');
}

export function renderMarkdown(source) {
  const { instance, math } = createRenderer();
  let html = instance.parse(prepare(source));
  html = DOMPurify.sanitize(html, {
    ADD_ATTR: ['target'],
    ALLOWED_URI_REGEXP: /^(?:(?:https?|mailto|dsh-resource):|[^a-z]|[a-z+.-]+(?:[^a-z+.-:]|$))/i,
  });
  // Formula markup is generated by KaTeX itself after sanitisation; user text
  // never reaches the KaTeX HTML as markup.
  return html.replace(/PDMATHTOKEN(\d+)ZZ/g, (token, index) => math[Number(index)] ?? token);
}

export function plainText(source, limit = 180) {
  return String(source || '')
    .replace(/\$\$[\s\S]*?\$\$/g, ' [formula] ')
    .replace(/\\\[[\s\S]*?\\\]/g, ' [formula] ')
    .replace(/\\\([\s\S]*?\\\)/g, ' [formula] ')
    .replace(/\$[^$\n]+\$/g, ' [formula] ')
    .replace(/```[\s\S]*?```/g, ' ')
    .replace(/[`*_>#-]/g, '')
    .replace(/\[([^\]]+)\]\([^)]+\)/g, '$1')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, limit);
}
